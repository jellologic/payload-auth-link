-- Target schema for the from-payload-auth importer test (issue #50):
-- the ba-* collections the payload-auth-link engine creates for a
-- plain (non-adopt) engine, generated from the catalog of a scratch
-- boot. The importer test applies this to the fixture database and
-- boots with push disabled.

CREATE TABLE IF NOT EXISTS ba_accounts (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  ba_id varchar NOT NULL,
  user_id varchar NOT NULL,
  account_id varchar NOT NULL,
  provider_id varchar NOT NULL,
  password varchar,
  access_token varchar,
  refresh_token varchar,
  id_token varchar,
  access_token_expires_at timestamptz,
  refresh_token_expires_at timestamptz,
  scope varchar,
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ba_accounts_pkey PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS ba_accounts_ba_id_idx ON public.ba_accounts USING btree (ba_id);
CREATE INDEX IF NOT EXISTS ba_accounts_user_id_idx ON public.ba_accounts USING btree (user_id);
CREATE INDEX IF NOT EXISTS ba_accounts_account_id_idx ON public.ba_accounts USING btree (account_id);
CREATE INDEX IF NOT EXISTS ba_accounts_provider_id_idx ON public.ba_accounts USING btree (provider_id);
CREATE INDEX IF NOT EXISTS ba_accounts_updated_at_idx ON public.ba_accounts USING btree (updated_at);
CREATE INDEX IF NOT EXISTS ba_accounts_created_at_idx ON public.ba_accounts USING btree (created_at);
ALTER TABLE payload_locked_documents_rels ADD COLUMN IF NOT EXISTS ba_accounts_id integer;

